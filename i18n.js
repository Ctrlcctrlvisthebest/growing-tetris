const REVERSE_TEXT = Object.fromEntries(Object.entries(ZH_TEXT).map(([en, zh]) => [zh, en]));
REVERSE_TEXT['START GAME · 开始游戏'] = 'START GAME';
const TEMPLATE_RULES = TEXT_TEMPLATES.map(([en, zh]) => {
  const key = en.match(/\{(\w+)\}/)[1];
  const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return { en, zh, key, pattern: new RegExp('^' + en.split('{' + key + '}').map(escape).join('(.+)') + '$') };
});
function validLanguage(value) { return value === 'zh-CN' || value === 'en'; }
function initialLanguage() {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (validLanguage(saved)) return saved;
  } catch (_) { /* Language switching remains available without storage. */ }
  return validLanguage(window.GROWING_TETRIS_DEFAULT_LANGUAGE) ? window.GROWING_TETRIS_DEFAULT_LANGUAGE : 'en';
}
let currentLanguage = initialLanguage();
function languageLocale() { return currentLanguage === 'zh-CN' ? 'zh-CN' : 'en-US'; }
function t(value) {
  const source = REVERSE_TEXT[value] || value;
  if (currentLanguage === 'en') return source;
  if (ZH_TEXT[source]) return ZH_TEXT[source];
  for (const rule of TEMPLATE_RULES) {
    const match = String(source).match(rule.pattern);
    if (match) return rule.zh.replace('{' + rule.key + '}', match[1]);
  }
  return source;
}
const languageTextNodes = [];
const languageAttributes = [];
const localizedElements = new Map();
function setLocalizedText(element, source) {
  if (!element) return;
  localizedElements.set(element, source);
  element.textContent = t(source);
}
function setLanguage(language, persist = true) {
  if (!validLanguage(language)) return;
  currentLanguage = language;
  if (persist) {
    try { window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language); } catch (_) { /* Session choice still applies. */ }
  }
  document.documentElement.lang = language;
  for (const [node, prefix, source, suffix] of languageTextNodes) {
    if (node.isConnected) node.data = prefix + t(source) + suffix;
  }
  for (const [element, name, source] of languageAttributes) element.setAttribute(name, t(source));
  for (const [element, source] of localizedElements) {
    if (element.isConnected) element.textContent = t(source);
    else localizedElements.delete(element);
  }
  for (const select of document.querySelectorAll('[data-language-select]')) select.value = language;
  if (typeof renderKeybindingsList === 'function') renderKeybindingsList();
  if (typeof updateDisplayedKeyLabels === 'function') updateDisplayedKeyLabels();
  if (typeof renderScoreHistory === 'function') renderScoreHistory();
  if (typeof renderToyRankings === 'function' && isToyLeaderboard()) renderToyRankings();
  if (typeof lastGlobalEntries !== 'undefined' && lastGlobalEntries) renderGlobalLeaderboard(lastGlobalEntries);
  // Repaint an idle canvas without advancing the game, resetting timers or replacing a run.
  if (typeof gameCanvas !== 'undefined' && gameCanvas) paintGame();
}
function initializeLanguage() {
  // Capture only the original UI text. Player names and later score rows are never scanned.
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement.closest('script, style, [data-language-select], [data-key-action]')) continue;
    const match = node.data.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match[2]) continue;
    const source = match[2].replace(/\s+/g, ' ');
    languageTextNodes.push([node, match[1], source, match[3]]);
  }
  for (const element of document.querySelectorAll('[aria-label], [title], [placeholder]')) {
    for (const name of ['aria-label', 'title', 'placeholder']) {
      if (element.hasAttribute(name)) languageAttributes.push([element, name, element.getAttribute(name)]);
    }
  }
  for (const select of document.querySelectorAll('[data-language-select]')) {
    select.addEventListener('change', () => setLanguage(select.value));
  }
  setLanguage(currentLanguage, false);
}
